#!/usr/bin/env python3
"""Generate ``native/preset_map_gen.go`` from the pinned uTLS version.

The Go preset map (name -> utls.ClientHelloID) cannot be built at runtime
because Go cannot enumerate package-level variables and ClientHelloID has
unexported fields. So we derive it from the uTLS source that ``native/go.mod``
pins, and drop any preset that uTLS cannot actually build (e.g. PSK presets that
need a session) by asking the freshly built engine.

Regenerate with ``make gen`` after bumping uTLS.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
NATIVE = os.path.join(ROOT, "native")
OUT = os.path.join(NATIVE, "preset_map_gen.go")
SRC = os.path.join(ROOT, "src")

# Names that are ClientHelloID values but are not selectable presets.
DENY = {"HelloCustom"}

HEADER = """\
// Code generated by tools/gen_presets.py; DO NOT EDIT.
//
// Maps uTLS preset names to ClientHelloIDs, derived from the uTLS version
// pinned in native/go.mod. Regenerate with `make gen` after bumping uTLS.

package main

import utls "github.com/refraction-networking/utls"

var presetByName = map[string]utls.ClientHelloID{
"""

FOOTER = "}\n"


def find_go() -> str:
    for cand in (os.environ.get("FREETLS_GO"), "go",
                 os.path.expanduser("~/.local/go/bin/go"),
                 "/usr/local/go/bin/go", "/opt/go/bin/go", "/opt/homebrew/bin/go"):
        if not cand:
            continue
        if os.path.isabs(cand):
            if os.path.exists(cand):
                return cand
        else:
            found = shutil.which(cand)
            if found:
                return found
    raise SystemExit("Go toolchain not found; set FREETLS_GO=/path/to/go")


def utls_dir(go: str) -> str:
    env = dict(os.environ, PATH=os.path.dirname(go) + os.pathsep + os.environ.get("PATH", ""))
    env.setdefault("GOPATH", os.path.expanduser("~/go"))
    out = subprocess.run(
        [go, "list", "-m", "-f", "{{.Dir}}", "github.com/refraction-networking/utls"],
        cwd=NATIVE, capture_output=True, text=True, env=env,
    )
    d = out.stdout.strip()
    if out.returncode != 0 or not d or not os.path.isdir(d):
        raise SystemExit(
            "could not locate the uTLS module; run `cd native && go mod download` first"
        )
    return d


def discover(directory: str) -> list[str]:
    text = open(os.path.join(directory, "u_common.go"), encoding="utf-8").read()
    # Match both `HelloX = ClientHelloID{...}` and aliases `HelloX = HelloY`.
    names = re.findall(
        r"\b(Hello[A-Za-z0-9_]+)\s*=\s*(?:ClientHelloID\{|Hello[A-Za-z0-9_]+\b)", text
    )
    return sorted({n for n in names if n not in DENY})


def write_map(names: list[str]) -> None:
    body = "".join(f'\t"{n}": utls.{n},\n' for n in names)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(HEADER + body + FOOTER)


def build(go: str) -> None:
    env = dict(os.environ)
    env.setdefault("GOPATH", os.path.expanduser("~/go"))
    env["CGO_ENABLED"] = "1"
    env["PATH"] = os.path.dirname(go) + os.pathsep + env.get("PATH", "")
    subprocess.run(
        [go, "build", "-buildmode=c-shared", "-o", "libfreetls.so", "."],
        cwd=NATIVE, check=True, env=env,
    )


def unbuildable() -> list[str]:
    """Ask the freshly built engine which presets fail to produce a ClientHello."""
    sys.path.insert(0, SRC)
    os.environ["FREETLS_LIB"] = os.path.join(NATIVE, "libfreetls.so")
    try:
        from freetls import engine
    except Exception as exc:  # noqa: BLE001
        sys.stderr.write(f"warning: skipping prune ({exc})\n")
        return []
    return [n for n in engine.preset_list() if not engine.preset_raw(n)]


def main() -> int:
    go = find_go()
    directory = utls_dir(go)
    names = discover(directory)
    if not names:
        raise SystemExit(f"no presets found in {directory}/u_common.go")

    write_map(names)
    print(f"[gen] {len(names)} presets discovered in uTLS")

    build(go)
    dead = unbuildable()
    if dead:
        names = [n for n in names if n not in set(dead)]
        write_map(names)
        build(go)
        print(f"[gen] pruned {len(dead)} unbuildable presets: {', '.join(dead)}")

    print(f"[ok] wrote {len(names)} presets -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
