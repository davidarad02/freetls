"""The common-JA4 profile catalog, plus runtime-registered profiles.

The built-in catalog is generated by ``tools/gen_catalog.py`` from uTLS's real
ClientHello presets plus realistic variants (HTTP/1.1-only, no ALPN, no SNI).
Each entry reproduces its stored JA4 exactly.

You can also register your own profiles at runtime — either from a uTLS preset
name or from a full uTLS ``ClientHelloSpec`` JSON document — with
:func:`add_profile` / :func:`load_file`, so new/arbitrary fingerprints need no
code changes.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from functools import lru_cache

_DIR = os.path.dirname(os.path.abspath(__file__))
_CATALOG = os.path.join(_DIR, "catalog.json")


@dataclass(frozen=True)
class Profile:
    name: str
    alias: str
    preset: str | None = None
    no_sni: bool = False
    alpn: list | None = None
    ja4: str = ""
    ja4_a: str = ""
    ja3: str = ""
    chlo_json: str | None = None

    def spec(self, server_name: str | None = None, verify: bool | None = None):
        """Return a :class:`~freetls.model.FingerprintSpec` for this profile."""
        from ..model import FingerprintSpec

        if self.chlo_json is not None:
            return FingerprintSpec(
                chlo_json=self.chlo_json,
                server_name=server_name,
                verify=verify,
            )
        return FingerprintSpec(
            preset=self.preset,
            preset_no_sni=self.no_sni,
            preset_alpn=None if self.alpn is None else list(self.alpn),
            server_name=server_name,
            verify=verify,
        )


# Runtime-registered profiles: _EXTRA maps every name/alias -> Profile for
# lookups; _REGISTERED is keyed by alias for listing/dedup.
_EXTRA: dict[str, Profile] = {}
_REGISTERED: dict[str, Profile] = {}


@lru_cache(maxsize=1)
def _load() -> dict:
    with open(_CATALOG, encoding="utf-8") as fh:
        return json.load(fh)


@lru_cache(maxsize=1)
def _by_key() -> dict:
    out = {}
    for p in _load()["profiles"]:
        prof = Profile(**p)
        out[prof.alias] = prof
        out[prof.name] = prof
    out.update(_EXTRA)
    return out


def _invalidate() -> None:
    _by_key.cache_clear()


def _compute_fingerprints(
    *, preset: str | None, no_sni: bool, alpn, chlo_json: str | None
) -> tuple[str, str, str]:
    """Return (ja4, ja4_a, ja3) computed from the engine, offline."""
    from .. import engine
    from ..fingerprint import ja3_from_bytes, ja4_from_bytes

    if chlo_json is not None:
        raw = engine.chlo_raw(chlo_json)  # raises SpecError with the reason
    elif preset is not None:
        raw = engine.preset_raw_opts(preset, no_sni=no_sni, alpn=alpn)
    else:
        return "", "", ""
    if not raw:
        raise ValueError(f"could not build a ClientHello for preset {preset!r}")
    j4 = ja4_from_bytes(raw)
    j3 = ja3_from_bytes(raw)
    return j4["ja4"], j4["ja4_a"], j3["ja3"]


def add_profile(
    name: str,
    *,
    alias: str | None = None,
    preset: str | None = None,
    chlo_json: str | None = None,
    no_sni: bool = False,
    alpn: list | None = None,
    ja4: str | None = None,
    ja3: str | None = None,
) -> Profile:
    """Register a profile at runtime and return it.

    Provide either ``preset`` (a uTLS preset name such as ``"HelloChrome_155"``)
    or ``chlo_json`` (a uTLS ClientHelloSpec JSON document). ``ja4``/``ja3`` are
    computed from the engine when omitted. The profile becomes visible via
    :func:`get`, :func:`names` and :func:`list_profiles`.
    """
    if (preset is None) == (chlo_json is None):
        raise ValueError("provide exactly one of preset= or chlo_json=")
    alias = alias or _alias_for(name)
    profile = Profile(
        name=name,
        alias=alias,
        preset=preset,
        no_sni=no_sni,
        alpn=alpn,
        ja4=ja4 or "",
        ja4_a="",
        ja3=ja3 or "",
        chlo_json=chlo_json,
    )
    if not profile.ja4 or not profile.ja3:
        c_ja4, c_ja4a, c_ja3 = _compute_fingerprints(
            preset=preset, no_sni=no_sni, alpn=alpn, chlo_json=chlo_json
        )
        profile = Profile(
            name=name,
            alias=alias,
            preset=preset,
            no_sni=no_sni,
            alpn=alpn,
            ja4=profile.ja4 or c_ja4,
            ja4_a=c_ja4a,
            ja3=profile.ja3 or c_ja3,
            chlo_json=chlo_json,
        )
    _EXTRA[alias] = profile
    _EXTRA[name] = profile
    _REGISTERED[alias] = profile
    _invalidate()
    return profile


def load_file(path: str) -> int:
    """Register profiles from a JSON file (a list, or ``{"profiles": [...]}``).

    Each entry accepts the :func:`add_profile` fields. Returns the count loaded.
    """
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    entries = data["profiles"] if isinstance(data, dict) else data
    allowed = {"alias", "preset", "chlo_json", "no_sni", "alpn", "ja4", "ja3"}
    n = 0
    for e in entries:
        e = dict(e)
        name = e.pop("name")
        add_profile(name, **{k: v for k, v in e.items() if k in allowed})
        n += 1
    return n


def _alias_for(preset_or_name: str) -> str:
    base = preset_or_name
    if base.startswith("Hello"):
        base = base[len("Hello") :]
    return base.lower()


def list_profiles() -> list:
    """All profiles: the built-in catalog plus any registered at runtime."""
    builtin = [Profile(**p) for p in _load()["profiles"]]
    return builtin + list(_REGISTERED.values())


def names() -> list:
    return [p.alias for p in list_profiles()]


def get(name_or_alias: str) -> Profile | None:
    return _by_key().get(name_or_alias)


def find_ja4(query: str, *, limit: int = 25) -> list:
    """Profiles whose JA4 equals, starts with, or contains ``query``."""
    q = query.strip().lower()
    if not q:
        return []
    out = []
    for p in list_profiles():
        if not p.ja4:
            continue
        j = p.ja4.lower()
        if j == q or j.startswith(q) or q in j:
            out.append(p)
        if len(out) >= limit:
            break
    return out


def search(query: str, *, limit: int = 25) -> list:
    """Profiles whose name, alias or JA3 contains ``query`` (case-insensitive)."""
    q = query.strip().lower()
    if not q:
        return []
    out = []
    for p in list_profiles():
        if q in p.name.lower() or q in p.alias.lower() or q in p.ja3.lower():
            out.append(p)
        if len(out) >= limit:
            break
    return out


def export(profiles=None) -> list:
    """Return the profiles (all by default) as JSON-serialisable dicts."""
    from dataclasses import asdict

    profs = list_profiles() if profiles is None else list(profiles)
    return [asdict(p) for p in profs]


def save_file(path: str, profiles=None) -> int:
    """Write profiles to a JSON file loadable by :func:`load_file`."""
    data = export(profiles)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump({"profiles": data}, fh, indent=2)
        fh.write("\n")
    return len(data)


def spec(name_or_alias: str, server_name: str | None = None, verify: bool | None = None):
    prof = get(name_or_alias)
    if prof is None:
        raise KeyError(f"unknown profile: {name_or_alias!r}")
    return prof.spec(server_name=server_name, verify=verify)


def h2_bundle(
    name_or_alias: str,
    *,
    settings=None,
    window_update: int | None = None,
    pseudo_header_order=None,
    server_name: str | None = None,
    verify: bool | None = None,
):
    """Return a profile spec with HTTP/2 fingerprint controls applied."""
    prof_spec = spec(name_or_alias, server_name=server_name, verify=verify)
    if settings is not None:
        prof_spec.h2_settings = [list(s) for s in settings]
    if window_update is not None:
        prof_spec.h2_window_update = int(window_update)
    if pseudo_header_order is not None:
        prof_spec.h2_pseudo_header_order = list(pseudo_header_order)
    return prof_spec


def catalog_info() -> dict:
    d = _load()
    return {
        "count": d["count"],
        "distinct_ja4": len({p["ja4"] for p in d["profiles"]}),
        "registered": len(_REGISTERED),
        "total": d["count"] + len(_REGISTERED),
        "generated_by": d.get("generated_by"),
        "engine_version": d.get("engine_version"),
    }
