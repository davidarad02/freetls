"""The built-in common-JA4 profile catalog.

Generated by ``tools/gen_catalog.py`` from uTLS's real ClientHello presets plus
realistic variants (HTTP/1.1-only, no ALPN, no SNI). Each entry reproduces its
stored JA4 exactly.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass
from functools import lru_cache
from typing import Optional

_DIR = os.path.dirname(os.path.abspath(__file__))
_CATALOG = os.path.join(_DIR, "catalog.json")


@dataclass(frozen=True)
class Profile:
    name: str
    alias: str
    preset: str
    no_sni: bool
    alpn: Optional[list]
    ja4: str
    ja4_a: str
    ja3: str

    def spec(self, server_name: Optional[str] = None, verify: bool = False):
        """Return a :class:`~freetls.model.FingerprintSpec` for this profile."""
        from ..model import FingerprintSpec

        return FingerprintSpec(
            preset=self.preset,
            preset_no_sni=self.no_sni,
            preset_alpn=None if self.alpn is None else list(self.alpn),
            server_name=server_name,
            verify=verify,
        )


@lru_cache(maxsize=1)
def _load() -> dict:
    with open(_CATALOG, encoding="utf-8") as fh:
        return json.load(fh)


@lru_cache(maxsize=1)
def _by_key() -> dict:
    out = {}
    for p in _load()["profiles"]:
        prof = Profile(**p)
        out[prof.alias] = prof
        out[prof.name] = prof
    return out


def list_profiles() -> list:
    """All profiles in the catalog."""
    return [Profile(**p) for p in _load()["profiles"]]


def names() -> list:
    return [p.alias for p in list_profiles()]


def get(name_or_alias: str) -> Optional[Profile]:
    return _by_key().get(name_or_alias)


def spec(name_or_alias: str, server_name: Optional[str] = None, verify: bool = False):
    prof = get(name_or_alias)
    if prof is None:
        raise KeyError(f"unknown profile: {name_or_alias!r}")
    return prof.spec(server_name=server_name, verify=verify)


def catalog_info() -> dict:
    d = _load()
    return {
        "count": d["count"],
        "distinct_ja4": len({p["ja4"] for p in d["profiles"]}),
        "generated_by": d.get("generated_by"),
        "engine_version": d.get("engine_version"),
    }
