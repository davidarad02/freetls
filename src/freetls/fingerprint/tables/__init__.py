"""IANA-sourced value universe for freetls (assigned values only).

Tables are generated by tools/gen_tables.py and committed so the library
runtime never needs network access.

Besides value/name lookups, this module provides coercion helpers
(``as_cipher``, ``as_extension``, ``as_sigalg``, ``as_group``) that accept an
int, an ``IntEnum`` member, or a case-insensitive name string.
"""

from __future__ import annotations

import json
import os
from functools import cache

_DIR = os.path.dirname(os.path.abspath(__file__))


@cache
def _load(name: str) -> dict:
    with open(os.path.join(_DIR, f"{name}.json"), encoding="utf-8") as fh:
        return json.load(fh)


def _tables(name: str):
    data = _load(name)
    entries = data["entries"]
    by_value = {e["value"]: e for e in entries}
    by_name = {e["name"]: e for e in entries}
    return entries, by_value, by_name


CIPHERS, CIPHERS_BY_VALUE, CIPHERS_BY_NAME = _tables("ciphers")
EXTENSIONS, EXTENSIONS_BY_VALUE, EXTENSIONS_BY_NAME = _tables("extensions")
SIGALGS, SIGALGS_BY_VALUE, SIGALGS_BY_NAME = _tables("sigalgs")
GROUPS, GROUPS_BY_VALUE, GROUPS_BY_NAME = _tables("groups")


def cipher_name(value: int) -> str | None:
    e = CIPHERS_BY_VALUE.get(int(value))
    return e["name"] if e else None


def extension_name(value: int) -> str | None:
    e = EXTENSIONS_BY_VALUE.get(int(value))
    return e["name"] if e else None


def sigalg_name(value: int) -> str | None:
    e = SIGALGS_BY_VALUE.get(int(value))
    return e["name"] if e else None


def group_name(value: int) -> str | None:
    e = GROUPS_BY_VALUE.get(int(value))
    return e["name"] if e else None


def cipher_value(name: str) -> int | None:
    e = CIPHERS_BY_NAME.get(name)
    return e["value"] if e else None


def extension_value(name: str) -> int | None:
    e = EXTENSIONS_BY_NAME.get(name)
    return e["value"] if e else None


def sigalg_value(name: str) -> int | None:
    e = SIGALGS_BY_NAME.get(name)
    return e["value"] if e else None


def group_value(name: str) -> int | None:
    e = GROUPS_BY_NAME.get(name)
    return e["value"] if e else None


def _coerce(value, by_name: dict, table: str) -> int:
    if isinstance(value, bool):  # bool is an int subclass; reject it
        raise TypeError(f"{table} value must be an int, name, or enum, not bool")
    if isinstance(value, int):
        return int(value)
    if isinstance(value, str):
        e = by_name.get(value)
        if e is None:
            lowered = value.lower()
            for name, entry in by_name.items():
                if name.lower() == lowered:
                    e = entry
                    break
        if e is None:
            raise ValueError(f"unknown {table} name: {value!r}")
        return int(e["value"])
    raise TypeError(f"{table} value must be an int, name, or enum, got {type(value).__name__}")


def as_cipher(value) -> int:
    """Coerce a cipher suite int, IntEnum member, or name -> int."""
    return _coerce(value, CIPHERS_BY_NAME, "cipher")


def as_extension(value) -> int:
    """Coerce an extension type int, IntEnum member, or name -> int."""
    return _coerce(value, EXTENSIONS_BY_NAME, "extension")


def as_sigalg(value) -> int:
    """Coerce a signature scheme int, IntEnum member, or name -> int."""
    return _coerce(value, SIGALGS_BY_NAME, "signature scheme")


def as_group(value) -> int:
    """Coerce a named-group int, IntEnum member, or name -> int."""
    return _coerce(value, GROUPS_BY_NAME, "named group")


def universe() -> dict:
    """Return the assigned-value universe and its theoretical size."""
    return {
        "ciphers": [e["value"] for e in CIPHERS],
        "extensions": [e["value"] for e in EXTENSIONS],
        "sigalgs": [e["value"] for e in SIGALGS],
        "groups": [e["value"] for e in GROUPS],
        "counts": {
            "ciphers": len(CIPHERS),
            "extensions": len(EXTENSIONS),
            "sigalgs": len(SIGALGS),
            "groups": len(GROUPS),
        },
    }
